function retrato(int $id): array
{
    global $tabelasLocais;
    $dados = [];
    foreach (array_merge(['estabelecimento'], $tabelasLocais) as $tabela) {
        $q = bd()->prepare('SELECT * FROM ' . $tabela . ' WHERE id_estabelecimento = ?');
        $q->execute([$id]);
        $dados[$tabela] = $q->fetchAll();
    }
    return $dados;
}
