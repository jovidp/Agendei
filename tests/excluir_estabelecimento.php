function inserir(string $tabela, array $dados): int
{
    $q = bd()->prepare('INSERT INTO ' . $tabela . ' (' . implode(',', array_keys($dados)) . ') VALUES (' . implode(',', array_fill(0, count($dados), '?')) . ')');
    $q->execute(array_values($dados));
    return (int) bd()->lastInsertId();
}

